/* Русская микротипографика для строк интерфейса: неразрывные пробелы после
   коротких предлогов/союзов, перед единицами и тире. nb('в 2 раза — это') */
const NB = ' ';
export const nb = (str) => String(str)
  .replace(/(^|[\s(«>])([а-яёА-ЯЁa-zA-Z]{1,3})\s(?=\S)/g, `$1$2${NB}`)
  .replace(/(\d)\s(?=(?:млн|ден|п\.п|мес|%|лет|раз|тыс|чел|ед\.))/g, `$1${NB}`)
  .replace(/\s—\s/g, `${NB}— `)
  .replace(/\s(?=(?:—|%))/g, NB);
